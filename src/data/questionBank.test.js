function buildValidQuestion(overrides = {}) {
  return {
    id: 'trex-01',
    dinosaur: DINOSAURS.TREX,
    question: '¿De qué se alimentaba el Tyrannosaurus Rex?',
    options: ['Solo de plantas', 'De carne', 'Solo de insectos', 'De algas del mar'],
    correctAnswerIndex: 1,
    dato_curioso: 'funFacts.trex-01',
    image: 'dinosaurs/trex.png',
    imageRealistic: 'realistic/trex.svg',
    imageFallback: 'fallback/trex.svg',
    imageAlt: 'Ilustración educativa de un Tyrannosaurus Rex.',
    level: 1,
    ...overrides,
  };
}

function buildMemoryLogService() {
  const events = [];
  return {
    events,
    logEvent(eventType, metadata) {
      events.push({ eventType, metadata });
    },
  };
}

// `fs.mkdtempSync` creates a fresh, uniquely-named directory whose random
// suffix is generated by the OS -- no user/process-derived input flows into
// `path.join`, so the joined segments are constant string literals and there
// is no path-traversal surface (semgrep path-join-resolve-traversal).
function createTempPath(prefix) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  return path.join(dir, 'questions.json');
}
function writeTempQuestionBank(questions) {
  const filePath = createTempPath('dinoquiz-questions-');
  fs.writeFileSync(filePath, JSON.stringify(questions), 'utf-8');
  return filePath;
}

// Rejects traversal segments/absolute paths in an "image" field pulled from the
// question bank JSON before it is ever joined onto a filesystem path.
function sanitizeImageReference(imageRef) {
  if (typeof imageRef !== 'string' || imageRef.indexOf('..') !== -1) {
    throw new Error(`Invalid image reference: ${imageRef}`);
  }
  const isAllowedRelativePath = /^[a-zA-Z0-9][a-zA-Z0-9/_-]*\.(png|jpg|jpeg|svg|webp)$/.test(imageRef);
  if (!isAllowedRelativePath) {
    throw new Error(`Invalid image reference: ${imageRef}`);
  }
  return imageRef;
}

describe('real question bank (public/data/questions.json)', () => {
  const questions = loadQuestionBank();

  test('loads exactly the expected number of questions', () => {
    expect(questions).toHaveLength(EXPECTED_QUESTION_COUNT);
  });

  // TRIOFSND-202: build-time content check — the bank must contain exactly
  // 300 valid questions, 30 per level (1-10).
  test('TRIOFSND-202: contains exactly 300 valid questions, 30 per level', () => {
    expect(questions).toHaveLength(300);
    expect(getLevelCoverageErrors(questions)).toEqual([]);

    VALID_LEVELS.forEach((level) => {
      const levelQuestions = questions.filter((question) => question.level === level);
      expect(levelQuestions).toHaveLength(QUESTIONS_PER_LEVEL);
    });
  });

  test('has no validation errors', () => {
    expect(validateQuestionBank(questions)).toEqual([]);
  });

  test('covers every required dinosaur with at least the minimum number of questions', () => {
    VALID_DINOSAURS.forEach((dinosaur) => {
      const dinosaurQuestions = getQuestionsByDinosaur(questions, dinosaur);
      expect(dinosaurQuestions.length).toBeGreaterThanOrEqual(MIN_QUESTIONS_PER_DINOSAUR);
    });
  });

  test('has all unique ids', () => {
    const ids = questions.map((question) => question.id);
    expect(new Set(ids).size).toBe(ids.length);
  });

  test('every question has 3-4 options and a valid correct answer index', () => {
    questions.forEach((question) => {
      expect(question.options.length).toBeGreaterThanOrEqual(MIN_OPTIONS);
      expect(question.options.length).toBeLessThanOrEqual(MAX_OPTIONS);
      expect(question.correctAnswerIndex).toBeGreaterThanOrEqual(0);
      expect(question.correctAnswerIndex).toBeLessThan(question.options.length);
    });
  });

  test('every question has a non-empty dato_curioso key and image reference', () => {
    questions.forEach((question) => {
      expect(question.dato_curioso.trim().length).toBeGreaterThan(0);
      expect(question.image.trim().length).toBeGreaterThan(0);
    });
  });

  function expectResolvesToRealImageFile(imageRef) {
    const imagesDir = path.join(__dirname, '..', '..', 'public', 'assets', 'images');
    // Reject anything but a relative, traversal-free path before it ever reaches path.join.
    expect(imageRef).toMatch(/^[a-zA-Z0-9][a-zA-Z0-9._/-]*$/);
    expect(imageRef).not.toMatch(/\.\./);

    const imagePath = path.join(imagesDir, sanitizeImageReference(imageRef));
    const relativeToImagesDir = path.relative(imagesDir, imagePath);
    expect(relativeToImagesDir.startsWith('..')).toBe(false);
    expect(path.isAbsolute(relativeToImagesDir)).toBe(false);
    expect(imagePath.startsWith(imagesDir + path.sep)).toBe(true);

    expect(fs.existsSync(imagePath)).toBe(true);
  }

  test('every question image reference resolves to a real file under public/assets/images', () => {
    questions.forEach((question) => expectResolvesToRealImageFile(question.image));
  });

  test('AW5: every question has a realistic variant, a fallback asset and a neutral alt text', () => {
    questions.forEach((question) => {
      expect(hasImageVariants(question)).toBe(true);
      expect(question.imageAlt.trim().length).toBeGreaterThan(0);
    });
  });

  test('every question imageRealistic and imageFallback resolve to real files under public/assets/images', () => {
    questions.forEach((question) => {
      expectResolvesToRealImageFile(question.imageRealistic);
      expectResolvesToRealImageFile(question.imageFallback);
    });
  });

  test('every question dato_curioso key resolves to a non-empty i18n string', () => {
    const strings = getStrings('es');
    expect(getDatoCuriosoTranslationErrors(questions, strings)).toEqual([]);
  });

  test('every one of the 14 covered species has a dato curioso on each of its questions', () => {
    const strings = getStrings('es');
    VALID_DINOSAURS.forEach((dinosaur) => {
      const dinosaurQuestions = getQuestionsByDinosaur(questions, dinosaur);
      expect(dinosaurQuestions.length).toBeGreaterThan(0);
      dinosaurQuestions.forEach((question) => {
        const text = resolveDatoCurioso(strings, question.dato_curioso);
        expect(typeof text).toBe('string');
        expect(text.trim().length).toBeGreaterThan(0);
      });
    });
  });

  // Mandatory content-integrity gate: fails this suite (and CI) if the real
  // bank breaks any of level-count/total-count, duplicate ids,
  // correctAnswerIndex range, dato_curioso i18n resolution, or an
  // image/imageRealistic/imageFallback reference that doesn't exist on disk.
  // Composed from the same building blocks as the more granular tests above
  // (kept separately for a precise failure message) so a broken content
  // update can never slip through with only some of them updated.
  test('integrity gate: exact level counts, unique ids, in-range correctAnswerIndex, resolvable dato_curioso keys and existing image assets', () => {
    expect(questions).toHaveLength(EXPECTED_QUESTION_COUNT);
    expect(getLevelCoverageErrors(questions)).toEqual([]);
    expect(validateQuestionBank(questions)).toEqual([]);
    expect(getDatoCuriosoTranslationErrors(questions, getStrings('es'))).toEqual([]);

    questions.forEach((question) => {
      expectResolvesToRealImageFile(question.image);
      expectResolvesToRealImageFile(question.imageRealistic);
      expectResolvesToRealImageFile(question.imageFallback);
    });
  });

  // TRIOFSND-202: getQuestionsByLevel() against the real bank on disk.
  // TRIOFSND-224: the usable pool additionally requires every question's
  // "dinosaur" to have a matching ficha in the real creature catalog
  // (public/data/creatures.json) -- which today only covers a subset of the
  // 14 species used across the bank, so a level whose questions reference an
  // uncatalogued species returns fewer than 30 (or zero), each excluded
  // entry logged as content_validation_failed with rule "dinosaurCatalog".
  // Derived from the real catalog/bank instead of a hardcoded count so this
  // test tracks catalog completeness automatically as creatures.json grows.
  test('TRIOFSND-224: getQuestionsByLevel only returns questions whose dinosaur has a catalog ficha', () => {
    const catalogIds = new Set(loadCreatureCatalog().map((creature) => creature.id));
    const uncataloguedQuestionIds = new Set(
      questions.filter((question) => !catalogIds.has(question.dinosaur)).map((question) => question.id)
    );
    expect(uncataloguedQuestionIds.size).toBeGreaterThan(0);

    VALID_LEVELS.forEach((level) => {
      // A fresh logService per level: getQuestionsByLevel validates the
      // whole raw bank (not just this level) on every call, so reusing one
      // logService across levels would double-count the same catalog gaps.
      const logService = buildMemoryLogService();
      const levelQuestions = getQuestionsByLevel(level, { logService });
      const expectedQuestions = questions.filter(
        (question) => question.level === level && catalogIds.has(question.dinosaur)
      );

      expect(levelQuestions.map((question) => question.id).sort()).toEqual(
        expectedQuestions.map((question) => question.id).sort()
      );
      expect(levelQuestions.every((question) => catalogIds.has(question.dinosaur))).toBe(true);

      const uncataloguedEvents = logService.events.filter((event) => event.metadata.rule === 'dinosaurCatalog');
      expect(uncataloguedEvents.map((event) => event.metadata.id).sort()).toEqual([...uncataloguedQuestionIds].sort());
    });
  });

  function normalizeQuestionText(text) {
    return text
      .trim()
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');
  }

  test('levels 6-10 do not reuse ids or normalized question text from levels 1-5', () => {
    const legacyQuestions = questions.filter((question) => question.level <= 5);
    const newQuestions = questions.filter((question) => question.level >= 6);

    expect(legacyQuestions).toHaveLength(150);
    expect(newQuestions).toHaveLength(150);

    const legacyIds = new Set(legacyQuestions.map((question) => question.id));
    const legacyTexts = new Set(legacyQuestions.map((question) => normalizeQuestionText(question.question)));

    newQuestions.forEach((question) => {
      expect(legacyIds.has(question.id)).toBe(false);
      expect(legacyTexts.has(normalizeQuestionText(question.question))).toBe(false);
    });
  });
});

describe('validateQuestion', () => {
  test('accepts a well-formed question', () => {
    expect(validateQuestion(buildValidQuestion(), 0)).toEqual([]);
  });

  test('rejects a missing id', () => {
    const errors = validateQuestion(buildValidQuestion({ id: '' }), 0);
    expect(errors.some((error) => error.includes('"id"'))).toBe(true);
  });

  test('rejects an unknown dinosaur', () => {
    const errors = validateQuestion(buildValidQuestion({ dinosaur: 'stegosaurus-rex-9000' }), 0);
    expect(errors.some((error) => error.includes('"dinosaur"'))).toBe(true);
  });

  test('rejects too few options', () => {
    const errors = validateQuestion(
      buildValidQuestion({ options: ['Solo dos', 'Opciones'], correctAnswerIndex: 0 }),
      0
    );
    expect(errors.some((error) => error.includes('"options"'))).toBe(true);
  });

  test('rejects too many options', () => {
    const errors = validateQuestion(
      buildValidQuestion({ options: ['Una', 'Dos', 'Tres', 'Cuatro', 'Cinco'], correctAnswerIndex: 0 }),
      0
    );
    expect(errors.some((error) => error.includes('"options"'))).toBe(true);
  });

  test('rejects duplicate options', () => {
    const errors = validateQuestion(
      buildValidQuestion({ options: ['Igual', 'Igual', 'Distinta'], correctAnswerIndex: 0 }),
      0
    );
    expect(errors.some((error) => error.includes('duplicate'))).toBe(true);
  });

  test('rejects a correctAnswerIndex out of range', () => {
    const errors = validateQuestion(buildValidQuestion({ correctAnswerIndex: 7 }), 0);
    expect(errors.some((error) => error.includes('correctAnswerIndex'))).toBe(true);
  });

  test('rejects a non-integer correctAnswerIndex', () => {
    const errors = validateQuestion(buildValidQuestion({ correctAnswerIndex: 1.5 }), 0);
    expect(errors.some((error) => error.includes('correctAnswerIndex'))).toBe(true);
  });

  test('rejects a missing dato_curioso', () => {
    const errors = validateQuestion(buildValidQuestion({ dato_curioso: '   ' }), 0);
    expect(errors.some((error) => error.includes('dato_curioso'))).toBe(true);
  });

  test('rejects a missing image reference', () => {
    const errors = validateQuestion(buildValidQuestion({ image: '' }), 0);
    expect(errors.some((error) => error.includes('image'))).toBe(true);
  });

  test.each([undefined, null, 0, MAX_LEVEL + 1, 1.5, '1'])('rejects an invalid "level" (%p)', (level) => {
    const errors = validateQuestion(buildValidQuestion({ level }), 0);
    expect(errors.some((error) => error.includes('"level"'))).toBe(true);
  });

  test.each(VALID_LEVELS)('accepts level %i', (level) => {
    expect(validateQuestion(buildValidQuestion({ level }), 0)).toEqual([]);
  });
});

describe('validateQuestionBank', () => {
  test('flags duplicate ids across questions', () => {
    const questions = [
      buildValidQuestion({ id: 'dup-1' }),
      buildValidQuestion({ id: 'dup-1', dinosaur: DINOSAURS.TRICERATOPS }),
    ];
    const errors = validateQuestionBank(questions);
    expect(errors.some((error) => error.includes('unique'))).toBe(true);
  });

  test('rejects a non-array payload', () => {
    expect(validateQuestionBank({ not: 'an array' })).toEqual(['The question bank must be an array of questions']);
  });

  test('rejects a bank with fewer than the expected number of questions by default', () => {
    const questions = Array.from({ length: EXPECTED_QUESTION_COUNT - 1 }, (_, index) =>
      buildValidQuestion({ id: `trex-${index}` })
    );

    const errors = validateQuestionBank(questions);

    expect(errors.some((error) => error.includes(`exactly ${EXPECTED_QUESTION_COUNT}`))).toBe(true);
  });

  test('rejects a bank with more than the expected number of questions by default', () => {
    const questions = Array.from({ length: EXPECTED_QUESTION_COUNT + 1 }, (_, index) =>
      buildValidQuestion({ id: `trex-${index}` })
    );

    const errors = validateQuestionBank(questions);

    expect(errors.some((error) => error.includes(`exactly ${EXPECTED_QUESTION_COUNT}`))).toBe(true);
  });

  test('allows opting out of the total count check', () => {
    const questions = [buildValidQuestion()];

    expect(validateQuestionBank(questions, { checkCount: false })).toEqual([]);
  });
});

describe('hasImageVariants (AW5)', () => {
  test('accepts a question with a realistic variant, a fallback asset and an alt text', () => {
    expect(hasImageVariants(buildValidQuestion())).toBe(true);
  });

  test.each(['imageRealistic', 'imageFallback', 'imageAlt'])('rejects a question missing "%s"', (field) => {
    expect(hasImageVariants(buildValidQuestion({ [field]: undefined }))).toBe(false);
  });

  test.each(['imageRealistic', 'imageFallback', 'imageAlt'])('rejects a question with a blank "%s"', (field) => {
    expect(hasImageVariants(buildValidQuestion({ [field]: '   ' }))).toBe(false);
  });

  test('rejects a nullish question', () => {
    expect(hasImageVariants(null)).toBe(false);
    expect(hasImageVariants(undefined)).toBe(false);
  });
});

describe('filterQuestionsWithImageVariants (AW5)', () => {
  test('keeps only questions that have both image variants and a fallback', () => {
    const complete = buildValidQuestion({ id: 'trex-01' });
    const missingRealistic = buildValidQuestion({ id: 'trex-02', imageRealistic: '' });
    const missingFallback = buildValidQuestion({ id: 'trex-03', imageFallback: undefined });
    const missingAlt = buildValidQuestion({ id: 'trex-04', imageAlt: '   ' });

    const filtered = filterQuestionsWithImageVariants([complete, missingRealistic, missingFallback, missingAlt]);

    expect(filtered).toEqual([complete]);
  });

  test('returns an empty array when no question has both variants', () => {
    const questions = [
      buildValidQuestion({ id: 'trex-01', imageRealistic: '' }),
      buildValidQuestion({ id: 'trex-02', imageFallback: '' }),
    ];

    expect(filterQuestionsWithImageVariants(questions)).toEqual([]);
  });
});

describe('getDinosaurCoverageErrors', () => {
  test('flags a dinosaur with fewer than the minimum required questions', () => {
    const questions = [
      buildValidQuestion({ id: 'trex-01', dinosaur: DINOSAURS.TREX }),
      buildValidQuestion({ id: 'triceratops-01', dinosaur: DINOSAURS.TRICERATOPS }),
      buildValidQuestion({ id: 'triceratops-02', dinosaur: DINOSAURS.TRICERATOPS }),
      buildValidQuestion({ id: 'triceratops-03', dinosaur: DINOSAURS.TRICERATOPS }),
    ];

    const errors = getDinosaurCoverageErrors(questions);

    expect(errors.some((error) => error.includes(DINOSAURS.TREX))).toBe(true);
    expect(errors.some((error) => error.includes(DINOSAURS.TRICERATOPS))).toBe(false);
  });

  test('returns no errors when every dinosaur meets the minimum', () => {
    const questions = VALID_DINOSAURS.flatMap((dinosaur) =>
      Array.from({ length: MIN_QUESTIONS_PER_DINOSAUR }, (_, questionIndex) =>
        buildValidQuestion({ id: `${dinosaur}-${questionIndex}`, dinosaur })
      )
    );

    expect(getDinosaurCoverageErrors(questions)).toEqual([]);
  });
});

